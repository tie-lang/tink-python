"""test_tink_v3.py —— KAT tests for tink_v3.py.

Vectors are generated by the tie reference implementation (`tlib/std/tink_v3.tie`)
and must match byte-for-byte (same vector set as tink_v3.c and the Rust/Java
ports).

Run: python test_tink_v3.py
"""

import sys

import tink_v3 as t

failures = 0


def check(cond, name):
    global failures
    if cond:
        print("PASS", name)
    else:
        failures += 1
        print("FAIL", name)


def pat(n):
    return bytes((i * 7 + 3) & 0xFF for i in range(n))


def test_crc_kat():
    check(t.crc32c(b"123456789") == 0xE3069283, "crc_123456789")
    check(t.crc32c(pat(9)) == 2452382926, "crc_pat9")
    check(t.crc32c(bytes(32)) == 2324772522, "crc_rfc_zeros")
    check(t.crc32c(b"\xff" * 32) == 1655221059, "crc_rfc_ff")
    check(t.crc32c(bytes(range(32))) == 1188919630, "crc_rfc_inc")


def test_single_frames():
    f = t.msg_encode(pat(13))
    check(f.hex() == "746b0304000c0000000000000000000d030a11181f262d343b424950571d47ab1e",
          "single_frame_13")
    f = t.msg_encode(bytes(range(32)))
    check(f.hex() == ("746b0304000c00000000000000000020000102030405060708090a0b0c0d0e0f"
                      "101112131415161718191a1b1c1d1e1fee038132"), "single_frame_32inc")
    f = t.msg_encode(b"")
    check(f.hex() == "746b0304000c00000000000000000000e7ccf215", "empty_frame")


def test_ext_frame():
    f = t.frame_encode_ext(b"x", bytes([0x00, 0x02, 0x00, 0x01, 0x05]))
    check(f.hex() == "746b0304000d000000000000000000010005000200010578479e613c", "ext_frame_kat")
    r = t.msg_decode(f, 0)
    check(r is not None and r[0] == b"x" and r[1] == len(f), "ext_frame_decode")


def test_fragmented():
    p = pat(70000)
    f = t.msg_encode(p)
    ok = len(f) == 70048
    ok = ok and f[:16].hex() == "746b030400140000000000000000ffff"
    ok = ok and f[65551:65555].hex() == "112dd201"
    ok = ok and f[65555:65575].hex() == "746b0304001c000000000000000111790000fffb"
    ok = ok and f[-4:].hex() == "38fb521f"
    check(ok, "fragmented_layout")
    r = t.msg_decode(f, 0)
    check(r is not None and r == (p, len(f)), "fragmented_roundtrip")
    bad = bytearray(f)
    bad[65600] ^= 0x01
    check(t.msg_decode(bytes(bad), 0) is None, "fragmented_tamper_reject")


def test_boundaries():
    p = pat(65535)
    f = t.frame_encode(p)
    ok = len(f) == 65555
    ok = ok and f[:16].hex() == "746b0304000c0000000000000000ffff"
    ok = ok and f[-4:].hex() == "4995f11e"
    check(ok, "max_single_65535")
    check(len(t.msg_encode(p[:65532])) == 65532 + 2 * 24, "boundary_65532_two_frags")
    # v1 frames are rejected (generational upgrade)
    v1 = bytes([0, 0, 0, 3, 0xAA, 0xBB, 0xCC, 0, 0, 0, 0])
    check(t.msg_decode(v1, 0) is None, "v1_rejected")


def main():
    test_crc_kat()
    test_single_frames()
    test_ext_frame()
    test_fragmented()
    test_boundaries()
    if failures == 0:
        print("ALL:PASS")
        return 0
    print(f"ALL:FAIL ({failures})")
    return 1


if __name__ == "__main__":
    sys.exit(main())
